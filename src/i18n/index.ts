const catalogs: Record<AppLocale, Catalog> = { en, ja, "zh-CN": zhCN };

export function normalizeLocale(value: string | null | undefined): AppLocale {
  const locale = value?.trim().toLowerCase().replaceAll("_", "-") ?? "";
  if (locale.startsWith("zh")) return "zh-CN";
  if (locale.startsWith("ja")) return "ja";
  return "en";
}

export function getExtensionLocale(): AppLocale {
  const browserLocale =
    typeof chrome !== "undefined" && chrome.i18n?.getUILanguage
      ? chrome.i18n.getUILanguage()
      : typeof navigator !== "undefined"
        ? navigator.language
        : "en";
  return normalizeLocale(browserLocale);
}

export function getDocumentLocale(doc: Document): AppLocale {
  return normalizeLocale(doc.documentElement.lang || getExtensionLocale());
}

export function translate(
  locale: AppLocale,
  key: MessageKey,
  values: Record<string, string | number> = {},
): string {
  return catalogs[locale][key].replace(/\{([a-zA-Z0-9_]+)\}/g, (match, name: string) =>
    Object.hasOwn(values, name) ? String(values[name]) : match,
  );
}

export function relationshipPresentation(
  locale: AppLocale,
  relationship: DisplayRelationship,
): { label: string; shortLabel: string; description: string } {
  const keys: Record<DisplayRelationship, readonly [MessageKey, MessageKey, MessageKey]> = {
    mutual: ["relationshipMutualLabel", "relationshipMutualShort", "relationshipMutualDescription"],
    following_only: ["relationshipFollowingOnlyLabel", "relationshipFollowingOnlyShort", "relationshipFollowingOnlyDescription"],
    follows_you_only: ["relationshipFollowsYouOnlyLabel", "relationshipFollowsYouOnlyShort", "relationshipFollowsYouOnlyDescription"],
    blocked_by: ["relationshipBlockedByLabel", "relationshipBlockedByShort", "relationshipBlockedByDescription"],
    unknown: ["relationshipUnknownLabel", "relationshipUnknownShort", "relationshipUnknownDescription"],
    none: ["relationshipNoneLabel", "relationshipNoneShort", "relationshipNoneDescription"],
    changed: ["relationshipChangedLabel", "relationshipChangedShort", "relationshipChangedDescription"],
    unfollowed_you: ["relationshipUnfollowedYouLabel", "relationshipUnfollowedYouShort", "relationshipUnfollowedYouDescription"],
    you_unfollowed: ["relationshipYouUnfollowedLabel", "relationshipYouUnfollowedShort", "relationshipYouUnfollowedDescription"],
    blocked_you: ["relationshipBlockedYouLabel", "relationshipBlockedYouShort", "relationshipBlockedYouDescription"],
  };
  const [label, shortLabel, description] = keys[relationship];
  return {
    label: translate(locale, label),
    shortLabel: translate(locale, shortLabel),
    description: translate(locale, description),
  };
}

export function sourceTypeLabel(locale: AppLocale, source: SourceType): string {
  const keys: Record<SourceType, MessageKey> = {
    profile: "sourceProfile",
    following: "sourceFollowing",
    followers: "sourceFollowers",
    timeline: "sourceTimeline",
    search: "sourceSearch",
    notifications: "sourceNotifications",
    thread: "sourceThread",
    unknown: "sourceUnknown",
  };
  return translate(locale, keys[source]);
}
